import { parseVnpayDate } from './vnpay-date.js';

describe('parseVnpayDate', () => {
  it.each([
    ['20261110123456', '2026-11-10T05:34:56.000Z'],
    ['20261110000000', '2026-11-09T17:00:00.000Z'],
    ['20260301065959', '2026-02-28T23:59:59.000Z'],
    ['20260101000000', '2025-12-31T17:00:00.000Z'],
    ['20240229070000', '2024-02-29T00:00:00.000Z'],
    ['20000229235959', '2000-02-29T16:59:59.000Z'],
    ['00010101070000', '0001-01-01T00:00:00.000Z'],
    ['00991231070000', '0099-12-31T00:00:00.000Z'],
  ])('parses %s as fixed GMT+7 time', (value, expected) => {
    expect(parseVnpayDate(value)?.toISOString()).toBe(expected);
  });

  it.each([
    null,
    undefined,
    '',
    '2026111012345',
    '202611101234567',
    '2026111012345x',
    ' 20261110123456',
    '20261110123456 ',
    '2026-11-10T12:34:56',
    '00000101000000',
    '20260001000000',
    '20261301000000',
    '20260100000000',
    '20260132000000',
    '20260431000000',
    '20260229000000',
    '19000229000000',
    '21000229000000',
    '20260230000000',
    '20261110240000',
    '20261110126000',
    '20261110123460',
  ])('rejects invalid or missing value %s', (value) => {
    expect(parseVnpayDate(value)).toBeNull();
  });
});
